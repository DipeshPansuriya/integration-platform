#!/bin/bash
# Whole-stack smoke boot on a build PC (NOT for the VPS). Takes the PC-wide docker-suite lock (mkdir protocol of
# ui/scripts/boot-backend.mjs: stale after 60 min), boots project `ipass-hosting-smoke` with dummy secrets in a temp
# env file, asserts the controls, tears everything down (volumes too) and releases the lock. Local images only:
#   IMAGE_TAG=<short-commit> bash deploy/hostinger/test/smoke.sh      (images ipass/<name>:<tag> must exist)
set -u
export MSYS_NO_PATHCONV=1   # git-bash must not rewrite /opt/... container paths
HERE="$(cd "$(dirname "$0")/.." && pwd)"
LOCK="${DOCKER_SUITE_LOCK:-/d/Projects/ipass/.docker-suite.lock}"
TAG="${IMAGE_TAG:?set IMAGE_TAG (local image tag)}"
P=ipass-hosting-smoke
TMP="$(mktemp -d)"; ENVF="$(cygpath -m "$TMP" 2>/dev/null || echo "$TMP")/s.cfg"; HW="$(cygpath -m "$HERE" 2>/dev/null || echo "$HERE")"
have_lock=0; fail=0
note() { printf '%s\n' "$*"; }
ok() { note "PASS $1"; }
bad() { note "FAIL $1"; fail=1; }
dc() { docker compose -p "$P" --env-file "$ENVF" -f "$HW/compose.yaml" -f "$HW/test/compose.smoke.yaml" --profile demo "$@"; }

release() {
  dc down -v --remove-orphans >/dev/null 2>&1
  rm -rf "$TMP"
  if [ $have_lock = 1 ]; then rm -rf "$LOCK"; note "lock released"; fi
}
trap release EXIT

# --- take the lock (wait up to 90 min, like the harness)
start=$(date +%s)
while ! mkdir "$LOCK" 2>/dev/null; do
  age=$(( $(date +%s) - $(stat -c %Y "$LOCK/owner" 2>/dev/null || date +%s) ))
  if [ -f "$LOCK/owner" ] && [ "$age" -gt 3600 ]; then note "stale lock ($age s) - removing"; rm -rf "$LOCK"; continue; fi
  [ $(( $(date +%s) - start )) -gt 5400 ] && { note "could not take the lock"; exit 2; }
  sleep 20
done
have_lock=1
echo "arjun ipass-hosting-smoke $(date -u +%FT%TZ) refreshed=$(date -u +%FT%TZ)" > "$LOCK/owner"
note "lock taken"

# --- dummy secrets, generated by the real bootstrap script (that is part of what is tested)
IPASS_DOMAIN=smoke.invalid IMAGE_TAG="$TAG" sh "$HERE/bootstrap-env.sh" "$ENVF" > /dev/null || { bad "bootstrap"; exit 1; }
{
  echo "IPASS_IMAGE_PREFIX=ipass"
  echo "IPASS_LOG_DRIVER=json-file"
  echo "KC_HOSTNAME=http://keycloak:8080"
  echo "OIDC_ISSUER_URI=http://keycloak:8080/realms/platform"
  echo "IPASS_PROFILES=showcase"
  echo "IPASS_DESTINATION_HOSTS=wiremock"
  echo "IPASS_SHOWCASE_LOCAL_HOSTS=wiremock"
  echo "IPASS_SHOWCASE_LOCAL_PORTS=8089"
} >> "$ENVF"

dc up -d --wait --wait-timeout 600 2>&1 | tail -15
dc ps -a --format '{{.Service}} {{.State}} {{.Health}}' | sort

# --- assertions
app_ready="$(dc exec -T platform-app wget -qO- http://127.0.0.1:8080/actuator/health/readiness 2>&1)"
case "$app_ready" in *'"UP"'*) ok "app readiness UP (K1 guard, Flyway, scheduler, KEK checks included)";; *) bad "app readiness: $app_ready"; dc logs --tail 60 platform-app;; esac
psqlx() { dc exec -T postgres sh -c 'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "$0"' "$1"; }
roles="$(psqlx "SELECT rolname||':'||rolsuper::int||':'||rolbypassrls::int||':'||rolcanlogin::int FROM pg_roles WHERE rolname LIKE 'ipa%' OR rolname='ipass_migrator' ORDER BY 1")"
note "$roles"
[ "$(echo "$roles" | grep -c .)" -ge 4 ] && echo "$roles" | grep -q '^ipass_app:0:0:1' && echo "$roles" | grep -q '^ipaas_app:0:0:0' && echo "$roles" | grep -q '^ipass_migrator:0:0:1' && ok "4-role split" || bad "4-role split"
[ "$(psqlx "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname='ipass'")" = ipass_migrator ] && ok "migrator owns the database" || bad "db owner"
[ "$(psqlx "SELECT count(*) FROM pg_class c JOIN pg_roles r ON r.oid=c.relowner WHERE r.rolname='ipass_app' AND c.relnamespace='public'::regnamespace AND c.relkind IN ('r','p')")" = 0 ] && ok "ipass_app owns no tenant table" || bad "ipass_app owns tables"
[ "$(psqlx "SELECT pg_has_role('ipass_app','ipaas_app','member')")" = t ] && ok "ipass_app is a member of ipaas_app" || bad "membership"
topics="$(dc exec -T kafka /opt/kafka/bin/kafka-topics.sh --bootstrap-server localhost:9092 --list 2>&1)"
for t in platform.message.accepted platform.delivery.due platform.poison; do grep -qx "$t" <<<"$topics" && ok "topic $t" || bad "topic $t"; done
kc="$(dc ps keycloak --format '{{.Health}}')"; [ "$kc" = healthy ] && ok "keycloak healthy (start --optimized)" || bad "keycloak $kc"
dc exec -T keycloak sh -c 'echo $KC_HTTP_ENABLED' >/dev/null 2>&1
curl -fsS "http://127.0.0.1:18081/realms/platform/.well-known/openid-configuration" | grep -q '"issuer":"http://keycloak:8080/realms/platform"' && ok "realm platform imported, issuer as configured" || bad "realm issuer"
dc exec -T platform-app wget -qO- http://wiremock:8089/__admin/health >/dev/null 2>&1 && ok "wiremock reachable from the app, internal only" || bad "wiremock"
# nothing published except the two loopback overrides
pub="$(docker ps --filter "label=com.docker.compose.project=$P" --format '{{.Names}} {{.Ports}}' | grep -E '0\.0\.0\.0|:::' )"
[ -z "$pub" ] && ok "no port published beyond 127.0.0.1" || bad "published: $pub"
# C1: the migrator login is refused by the K1 guard
set +e
c1="$(dc run --rm -T --no-deps -e DB_USERNAME=ipass_migrator -e "DB_PASSWORD=$(grep '^DB_MIGRATION_PASSWORD=' "$ENVF" | cut -d= -f2)" -e SERVER_PORT=8099 platform-app 2>&1 | tail -80)"
set -e
echo "$c1" | grep -q "must not own a tenant table" && ok "C1: app refuses to start as ipass_migrator" || { bad "C1 (no K1 refusal in the log)"; echo "$c1" | tail -8; }
# restore test and backup, as run on the server
dc exec -T pg-backup env RUN_ONCE=1 sh /scripts/backup.sh | tail -3
dc exec -T pg-backup sh /scripts/restore-test.sh && ok "C4: restore test counts equal" || bad "restore test"
# seed.sql with throw-away subjects, twice (idempotent)
for i in 1 2; do
  dc exec -T postgres sh -c 'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v issuer=http://keycloak:8080/realms/platform -v sub_admin_a=00000000-0000-0000-0000-00000000000a -v sub_cfg_a=00000000-0000-0000-0000-00000000000b -v sub_appr_a=00000000-0000-0000-0000-00000000000c -v sub_admin_b=00000000-0000-0000-0000-00000000000d -f -' < "$HERE/seed/seed.sql" > /dev/null
done
[ "$(psqlx "SELECT count(*) FROM public.app_user") $(psqlx "SELECT count(*) FROM public.role_grant")" = "4 4" ] && ok "seed.sql applies and is idempotent (4 users, 4 grants)" || bad "seed counts"
echo; [ $fail -eq 0 ] && note "SMOKE PASSED" || note "SMOKE FAILED"
exit $fail
